def get_noisy_weights(y, a_noisy):
    count_00 = max(np.sum((a_noisy==0) & (y==0)), 1)
    count_01 = max(np.sum((a_noisy==0) & (y==1)), 1)
    count_10 = max(np.sum((a_noisy==1) & (y==0)), 1)
    count_11 = max(np.sum((a_noisy==1) & (y==1)), 1)
    total = len(y)
    w = np.zeros(len(y))
    w[(a_noisy==0) & (y==0)] = total / (4 * count_00)
    w[(a_noisy==0) & (y==1)] = total / (4 * count_01)
    w[(a_noisy==1) & (y==0)] = total / (4 * count_10)
    w[(a_noisy==1) & (y==1)] = total / (4 * count_11)
    return torch.FloatTensor(w)

