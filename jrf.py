import random
import numpy as np
import pandas as pd
import torch
import torch.nn as nn
import torch.optim as optim
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score
from sklearn.datasets import fetch_openml
import warnings
warnings.filterwarnings("ignore")

# ==========================================
# 1. LOAD ADULT DATASET
# ==========================================
def load_adult():
    print("Loading Adult dataset for Lambda Sweep...")
    data = fetch_openml(data_id=1590, as_frame=True, parser='auto')
    X_raw = data.data
    y = (data.target == '>50K').astype(int).values
    A = (X_raw['sex'] == 'Male').astype(int).values
    X = X_raw.select_dtypes(include=['number']).fillna(0).values
    return StandardScaler().fit_transform(X), y, A

X, Y, A = load_adult()

# ==========================================
# 2. JRF JOINT LOSS FUNCTION (Eq. 5)
# ==========================================
def joint_robust_loss(y_pred, y_true_noisy, a_noisy, lambda_fair, rho_y, rho_a):
    # 1. Forward Loss for Label Noise (\rho_y)
    y_pred_fwd = (1 - rho_y) * y_pred + rho_y * (1 - y_pred)
    l_util = nn.BCELoss(reduction='mean')(y_pred_fwd, y_true_noisy.float().unsqueeze(1))

    # 2. MIRL for Attribute Noise (\rho_a)
    mask0, mask1 = (a_noisy == 0), (a_noisy == 1)
    if mask0.sum() == 0 or mask1.sum() == 0: return l_util
    mu0, mu1 = y_pred[mask0].mean(), y_pred[mask1].mean()

    if rho_a > 0.01:
        denom = max(1.0 - 2.0 * rho_a, 0.05)
        mu0_hat = ((1 - rho_a) * mu0 - rho_a * mu1) / denom
        mu1_hat = ((1 - rho_a) * mu1 - rho_a * mu0) / denom
        gap = torch.abs(mu0_hat - mu1_hat)
    else:
        gap = torch.abs(mu0 - mu1)

    return l_util + lambda_fair * gap

# ==========================================
# 3. HYPERPARAMETER SWEEP ENGINE
# ==========================================
def run_lambda_sweep():
    lambdas = [5.0, 10.0, 15.0, 20.0, 25.0]
    rho_y, rho_a = 0.3, 0.3 # 30% simultaneous noise
    n_seeds = 5

    print(f"\n{'='*80}")
    print(f"LAMBDA SENSITIVITY SWEEP (Adult Dataset | Noise=0.3 | 5 Seeds)")
    print(f"{'='*80}")
    print(f"{'Lambda':<10} | {'Accuracy (Mean ± Std)':<25} | {'Fairness Gap (Mean ± Std)':<25}")
    print("-" * 80)

    for lam in lambdas:
        accs = []
        gaps = []
        for s in range(n_seeds):
            random.seed(s); np.random.seed(s); torch.manual_seed(s)
            X_train, X_test, Y_train, Y_test, A_train, A_test = train_test_split(X, Y, A, test_size=0.3, random_state=s)

            # Inject 30% Noise (Train set only)
            mask_y = np.random.rand(len(Y_train)) < rho_y
            Y_tr_n = Y_train.copy(); Y_tr_n[mask_y] = 1 - Y_tr_n[mask_y]

            mask_a = np.random.rand(len(A_train)) < rho_a
            A_tr_n = A_train.copy(); A_tr_n[mask_a] = 1 - A_tr_n[mask_a]

            Xt = torch.FloatTensor(X_train)
            Yt = torch.FloatTensor(Y_tr_n)
            At = torch.FloatTensor(A_tr_n)
            Xtest = torch.FloatTensor(X_test)

            # 3-Layer MLP
            model = nn.Sequential(
                nn.Linear(X.shape[1], 32), nn.ReLU(),
                nn.Linear(32, 32), nn.ReLU(),
                nn.Linear(32, 1), nn.Sigmoid()
            )
            opt = optim.Adam(model.parameters(), lr=0.005)

            for epoch in range(50):
                opt.zero_grad()
                p = model(Xt)
                joint_robust_loss(p, Yt, At, lam, rho_y, rho_a).backward()
                opt.step()

            # Evaluate on clean test set
            with torch.no_grad():
                preds = (model(Xtest).numpy().flatten() > 0.5).astype(int)
                acc = accuracy_score(Y_test, preds)
                gap = abs(preds[A_test==0].mean() - preds[A_test==1].mean())
                accs.append(acc)
                gaps.append(gap)

        am, astd = np.mean(accs), np.std(accs)
        gm, gstd = np.mean(gaps), np.std(gaps)
        print(f"{lam:<10} | {am:.4f} ± {astd:.4f}             | {gm:.4f} ± {gstd:.4f}")

run_lambda_sweep()

